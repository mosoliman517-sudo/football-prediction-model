"""Builds online/schema_nba.sql: a full copy of every table and function (schema.sql ... schema_v11.sql) inside a separate `nba` schema.
Same Supabase project, same logins (auth.users), but profiles, ratings, results, badges, friends, ideas... are completely separate per sport.
The site picks the schema per request with the Accept-Profile / Content-Profile headers. Re-run this whenever a new schema_vN.sql is added."""
import re, glob, pathlib
files = sorted(glob.glob("online/schema.sql") + glob.glob("online/schema_v*.sql"), key=lambda f: (0 if f.endswith("schema.sql") else int(re.search(r"_v(\d+)", f).group(1))))
head = """-- ballknowledge BASKETBALL: a separate copy of every table and function, in its own schema called `nba`.
-- Logins are shared (Supabase Auth), everything else (nickname, rating, results, badges, friends, ideas, reports) is separate per sport.
-- Generated by src/62_make_nba_schema.py from schema.sql ... schema_v11.sql. Run once: Supabase -> SQL editor -> paste -> Run. Safe to run again.
-- The last lines of this file also expose the `nba` schema to the API, so nothing else needs clicking.

create schema if not exists nba;
grant usage on schema nba to anon, authenticated, service_role;
alter default privileges in schema nba grant all on tables to anon, authenticated, service_role;
alter default privileges in schema nba grant all on sequences to anon, authenticated, service_role;
alter default privileges in schema nba grant execute on functions to anon, authenticated, service_role;
"""
out = [head]
for f in files:
    s = open(f).read()
    s = re.sub(r"\bpublic\.", "nba.", s)
    s = re.sub(r"search_path\s*=\s*public\b", "search_path = nba", s)
    out.append(f"\n-- ======== {pathlib.Path(f).name} ========\n" + s)
out.append("""
-- basketball has its own game ids and a single league ("NBA"), so the football lists are replaced by plain patterns
alter table nba.results drop constraint if exists results_game_check;
alter table nba.results add constraint results_game_check check (game ~ '^[a-z0-9_]{2,24}$');
alter table nba.results drop constraint if exists results_league_check;
alter table nba.results add constraint results_league_check check (league ~ '^[A-Za-z0-9]{2,8}$');

-- admins are the same people in both sports
insert into nba.admins (user_id) select user_id from public.admins on conflict do nothing;
grant all on all tables in schema nba to anon, authenticated, service_role;
grant all on all sequences in schema nba to anon, authenticated, service_role;
grant execute on all functions in schema nba to anon, authenticated, service_role;
alter role authenticator set pgrst.db_schemas = 'public, graphql_public, storage, nba';
notify pgrst, 'reload config';
notify pgrst, 'reload schema';
""")
sql = "".join(out)
left = [m for m in re.findall(r".{0,40}\bpublic\b.{0,30}", sql) if "from public.admins" not in m and "schema_v" not in m]
pathlib.Path("online/schema_nba.sql").write_text(sql)
print("wrote online/schema_nba.sql", len(sql) // 1024, "KB from", [pathlib.Path(f).name for f in files])
print("remaining mentions of 'public':", left[:8])
