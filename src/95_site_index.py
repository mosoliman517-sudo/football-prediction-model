"""One search index for all three sports: every game and the main sections of football, basketball and chess, with a link
that opens each one. Read from the games lists in the page code, so a new game shows up in search after the next build.
Writes site/site_index.js (const SITE_INDEX = [...]); each build includes it. Run by the three build scripts."""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def games_from(text, start_marker):
    out = []
    for m in re.finditer(re.escape(start_marker), text):
        i = m.end(); depth = 1; j = i
        while j < len(text) and depth:
            depth += {"[": 1, "(": 1, "]": -1, ")": -1}.get(text[j], 0); j += 1
        for g in re.finditer(r'\{ id: "([a-z0-9]+)", name: "([^"]+)"(?:, modes: "([^"]*)")?(?:, tag: "([^"]*)")?', text[i:j]):
            out.append(g.groups())
    return out


def build():
    rd = lambda p: open(os.path.join(ROOT, p), encoding="utf-8").read()
    arena, nba_t, nba_o, chess = rd("site/arena_template.html"), rd("site/nba_template.html"), rd("site/nba_overlay.js"), rd("site/chess_template.html")
    idx, seen = [], set()
    def add(sport, kind, name, url, sub=""):
        k = (sport, name)
        if k in seen: return
        seen.add(k); idx.append({"s": sport, "k": kind, "n": name, "u": url, "d": sub[:110]})
    for gid, name, modes, tag in games_from(arena, "const QUIZ_GAMES = [") + games_from(arena, "const GAMES = ["):
        add("football", "Game", name, f"football/#games-all-leagues-{gid}", tag or modes or "")
    nba_games = games_from(nba_o, "QUIZ_GAMES.push(") + games_from(nba_o, "GAMES.push(")
    for gid, name, modes, tag in nba_games:
        add("basketball", "Game", name, f"basketball/#games-nba-{gid}", tag or modes or "")
    i = chess.index("const CG = ["); j = chess.index("\n];", i)
    for gid, g, name, tag in re.findall(r'\{ id: "([a-z0-9]+)", g: "([a-z]+)", ic: "[a-z]+", name: "([^"]+)"(?:, modes: "[^"]*")?, tag: "([^"]*)"', chess[i:j]):
        add("chess", "Game", name, f"chess/#go-{gid}", tag)
    for sport, pages in {
        "football": [("Games", "football/#games", "Every football game in one place"), ("Leaderboard", "football/#games-all-leagues-boards", "Seasons and all-time Elo"), ("Ranked online", "football/#games-all-leagues-ranked", "Play real people for Elo"), ("Weekly tournament", "football/#games-all-leagues-weekly", "Predict this week's real scores"), ("Live scores", "football/#games-all-leagues-live", "Today's matches"), ("Our model", "football/#lab", "How the prediction model works"), ("Title race", "football/#lab-premier-league-race", "Who wins the league"), ("Time machine", "football/#lab-premier-league-replay", "A season replayed beside the model"), ("Profile", "football/#profile", "Your stats, badges and friends"), ("Sticker album", "football/#album", "Collect every club and player"), ("Settings", "football/#settings", "Look, sidekick and sound")],
        "basketball": [("Games", "basketball/#games", "Every basketball game in one place"), ("Leaderboard", "basketball/#games-nba-boards", "Seasons and all-time Elo"), ("Ranked online", "basketball/#games-nba-ranked", "Play real people for Elo"), ("Our model", "basketball/#lab", "How the NBA model works"), ("Profile", "basketball/#profile", "Your stats, badges and friends"), ("Settings", "basketball/#settings", "Look, sidekick and sound")],
        "chess": [("Games", "chess/#go-games", "Every chess game"), ("Daily challenges", "chess/#go-daily", "A puzzle, a bar and a tactic every day"), ("Learn", "chess/#go-learn", "Lessons, openings, endgames"), ("Opening explorer", "chess/#go-explorer", "Master games for any opening"), ("Endgame trainer", "chess/#go-et", "Seven endings against Stockfish"), ("Guess the famous game", "chess/#go-famous", "Replay the classics move by move"), ("Weekly cup", "chess/#go-wk", "Five puzzles, the same for everyone"), ("Puzzle rush", "chess/#go-rush", "Three minutes, as many puzzles as you can"), ("Practise my mistakes", "chess/#go-mypz", "Your own blunders as puzzles"), ("Opening repertoire", "chess/#go-rep", "Drill opening lines with spaced repetition"), ("World rankings", "chess/#go-rank", "The FIDE top 100"), ("Championships", "chess/#go-champ", "World titles and the current match"), ("Simulate a match", "chess/#go-sim", "Anyone against anyone, 1,000 games"), ("Leaderboards", "chess/#go-board", "Best scores")],
    }.items():
        for n, u, d in pages:
            add(sport, "Page", n, u, d)
    js = "/* generated by src/95_site_index.py: every game and main page in all three sports, for search */\nconst SITE_INDEX = " + json.dumps(idx, ensure_ascii=False, separators=(",", ":")) + ";\n"
    open(os.path.join(ROOT, "site/site_index.js"), "w", encoding="utf-8").write(js)
    return idx


if __name__ == "__main__":
    ix = build()
    print({s: sum(1 for x in ix if x["s"] == s) for s in ("football", "basketball", "chess")})
